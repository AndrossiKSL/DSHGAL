/**
 * 组装台词侧的成人向约束。日常场景不该被这些词压住，所以只在
 * 关系已经推进、或玩家明确走 mature 路线时才挂上。
 */
export function adultSceneHint(level: number, route: string): string {
  if (level <= 1) return ''
  const tone = route === 'fall'
    ? '这条是沉沦线：她明知不该还是往前走，嘴上会有反话和挑衅，身体的应承比话更快。'
    : '这条是纯爱线：靠近是一步步来的，但每一步都在往前走，不会原地打转。'
  return [
    tone,
    '当前亲密阶段第 ' + level + ' 阶。这个阶数只用于你判断尺度，绝对不要在台词或旁白里提到阶段、进度、资格、界限这类词。',
    '尺度随阶段推进：越往后越直白，动作与生理反应写具体，不要停在气氛描写上。',
  ].join('\n')
}
