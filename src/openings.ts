export function openingPool(mode: OpeningMode): readonly OpeningPreset[] {
  return mode === 'nsfw' ? NSFW_OPENINGS : RANDOM_OPENINGS
}

/**
 * 随机取一条。`avoid` 传上一次用过的 id，避免连点两次拿到同一条——
 * 用户点「随机」的意图就是要换一个，返回同一条等于按钮坏了。
 */
export function pickOpening(
  mode: OpeningMode,
  avoid: string[] = [],
  rng: () => number = Math.random,
): OpeningPreset {
  const pool = openingPool(mode)
  const fresh = pool.filter(p => !avoid.includes(p.id))
  const list = fresh.length ? fresh : pool
  const index = Math.min(list.length - 1, Math.max(0, Math.floor(rng() * list.length)))
  return list[index]
}

export function openingById(id: string): OpeningPreset | undefined {
  return [...RANDOM_OPENINGS, ...NSFW_OPENINGS].find(p => p.id === id)
}
