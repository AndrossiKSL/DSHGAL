import {readFileSync,readdirSync,existsSync,mkdirSync,copyFileSync,writeFileSync} from 'node:fs'
import {dirname,join,resolve} from 'node:path'
import {fileURLToPath} from 'node:url'

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..')
const lock=JSON.parse(readFileSync(join(root,'package-lock.json'),'utf8'))
const direct=new Set(Object.keys(lock.packages[''].devDependencies||{}))
const runtime=new Set(['react','react-dom','scheduler','loose-envify','js-tokens','electron'])
const packages=new Map()
for(const [location,entry] of Object.entries(lock.packages)){
 if(!location)continue
 const directory=join(root,location),manifest=join(directory,'package.json')
 const installed=existsSync(manifest),pkg=installed?JSON.parse(readFileSync(manifest,'utf8')):entry
 const name=pkg.name||location.split('node_modules/').at(-1),version=pkg.version||entry.version,key=name+'@'+version
 if(packages.has(key))continue
 const repository=typeof pkg.repository==='string'?pkg.repository:pkg.repository?.url||''
 const license=typeof pkg.license==='string'?pkg.license:pkg.license?.type||entry.license||'SEE UPSTREAM LICENSE'
 const noticeFiles=[]
 if(installed){
  for(const file of readdirSync(directory,{withFileTypes:true})){
   if(!file.isFile()||!(/^(?:licen[cs]e|copying|notice|copyright)(?:[._-].*)?$/i.test(file.name)))continue
   const target='third_party/npm/'+name.replace(/^@/,'').replaceAll('/','__')+'@'+version+'/'+file.name
   mkdirSync(dirname(join(root,target)),{recursive:true});copyFileSync(join(directory,file.name),join(root,target));noticeFiles.push(target)
  }
 }
 packages.set(key,{name,version,license,repository:repository.replace(/^git\+/,'').replace(/\.git$/,''),registry:'https://www.npmjs.com/package/'+name+'/v/'+version,role:runtime.has(name)?'runtime or desktop runtime':direct.has(name)?'direct build tool':'transitive build tool',installed,noticeFiles})
}
const entries=[...packages.values()].sort((a,b)=>a.name.localeCompare(b.name)||a.version.localeCompare(b.version))
mkdirSync(join(root,'third_party'),{recursive:true})
writeFileSync(join(root,'third_party/dependencies.json'),JSON.stringify({schema:1,source:'package-lock.json and installed package metadata; optional platform packages may have no local license copy',packages:entries},null,2)+'\n')
const escape=value=>String(value).replaceAll('|','\\|')
writeFileSync(join(root,'third_party/DEPENDENCIES.md'),'# Locked dependency credits\n\nGenerated by `node scripts/collect-third-party.mjs`. Versions come from package-lock.json. Runtime and development dependencies are listed separately by role. Original license files are preserved when present locally; absent copies are explicitly indicated rather than invented. Electron also carries Chromium and Node notices in the desktop runtime.\n\n| Package | Version | License | Use | License evidence |\n| --- | --- | --- | --- | --- |\n'+entries.map(p=>'| ['+escape(p.name)+']('+p.registry+') | '+escape(p.version)+' | '+escape(p.license)+' | '+p.role+' | '+(p.noticeFiles.length?p.noticeFiles.map(file=>'['+file.split('/').at(-1)+']('+file.replace('third_party/','')+')').join(' · '):'Upstream package / optional platform artifact')+' |').join('\n')+'\n')
console.log(JSON.stringify({lockedPackages:entries.length,localLicenseCopies:entries.reduce((sum,p)=>sum+p.noticeFiles.length,0)}))
