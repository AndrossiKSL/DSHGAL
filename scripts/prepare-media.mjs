import {readFileSync,writeFileSync,mkdirSync,readdirSync} from 'node:fs'
import {dirname,resolve} from 'node:path'
import {fileURLToPath} from 'node:url'
import {createHash} from 'node:crypto'
import {DEFAULT_ART_KEYS,artFileName} from './art-manifest.mjs'

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..')
const manifestPath=resolve(root,'assets/packs/manifest.json')
const pack=JSON.parse(readFileSync(manifestPath,'utf8'))
// Other generated art (frames and keepsakes) used to duplicate bitmap bytes in JS.
const dir=resolve(root,'src/client')
let replaced=0
for(const name of readdirSync(dir).filter(n=>n.endsWith('.generated.ts')&&n!=='art.generated.ts')){
 const path=resolve(dir,name),before=readFileSync(path,'utf8')
 const after=before.replace(/data:image\/(png|webp|svg\+xml)(;base64)?,([^"'\s]+)/g,(url,type,base64,data)=>{
  const bytes=base64?Buffer.from(data,'base64'):Buffer.from(decodeURIComponent(data))
  const hash=createHash('sha256').update(bytes).digest('hex'),ext=type==='svg+xml'?'svg':type
  const file=`embedded/${hash}.${ext}`,dest=resolve(root,'assets/packs',file)
  mkdirSync(dirname(dest),{recursive:true});writeFileSync(dest,bytes)
  if(!pack.files.includes(file))pack.files.push(file)
  pack.sha256[file]=hash;replaced++
  return '/whale-galgame-media/'+file
 })
 if(after!==before)writeFileSync(path,after)
}
writeFileSync(manifestPath,JSON.stringify(pack,null,2)+'\n')
const {sha256,...runtime}=pack
writeFileSync(resolve(root,'src/art-packs.ts'),'/** Runtime art and strict media allowlist. */\nexport const ART_PACKS='+JSON.stringify(runtime)+' as const\n')
writeFileSync(resolve(root,'src/default-art.ts'),'/** Generated by prepare-media.mjs. */\nexport const DEFAULT_ART_FILES='+JSON.stringify(DEFAULT_ART_KEYS.map(artFileName))+' as const\n')
console.log(`Prepared ${DEFAULT_ART_KEYS.length} default media files; externalized ${replaced} image payloads.`)
